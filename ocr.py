# ---------------------------------------------------------------------------
# Job registry (shared implementation – see jobs.py)
# ---------------------------------------------------------------------------
_REGISTRY = jobs.JobRegistry({
    'total': 0,
    'processed': 0,
    'current_page': 0,
    'pages': [],            # per-page text, filled when done
    'pdf_name': None,
    'txt_name': None,
})


def new_job() -> str:
    return _REGISTRY.new()


def get_job(jid: str):
    return _REGISTRY.get(jid)


def cancel_job(jid: str) -> bool:
    return _REGISTRY.cancel(jid)


_patch = _REGISTRY.patch
_is_cancelled = _REGISTRY.is_cancelled


# ---------------------------------------------------------------------------
# Worker
# ---------------------------------------------------------------------------
def start_ocr_job(jid: str, src_pdf_path: str, pages_to_process: list[int],
                  lang: str, generated_dir: str, base_name: str = 'ocr',
                  cleanup_path: str | None = None) -> None:
    """Kick off the worker thread. Non-blocking."""
    t = threading.Thread(
        target=_worker,
        args=(jid, src_pdf_path, list(pages_to_process), lang, generated_dir,
              base_name, cleanup_path),
        daemon=True,
    )
    t.start()


def _worker(jid, src_pdf_path, pages_to_process, lang, generated_dir, base_name,
            cleanup_path=None):
    try:
        if not tesseract_available():
            raise OCRError(
                'Tesseract is not available on the server. On Debian/Ubuntu: '
                'apt install tesseract-ocr tesseract-ocr-eng.')
        if not poppler_available():
            raise OCRError(
                'pdf2image / poppler is not available on the server. Install '
                'poppler-utils and `pip install pdf2image`.')

        lang_code = _resolve_language(lang)

        reader = PdfReader(src_pdf_path)
        total_pages = len(reader.pages)
        if total_pages == 0:
            raise OCRError('The PDF has no pages.')

        target = sorted({p for p in pages_to_process if 1 <= p <= total_pages})
        if not target:
            raise OCRError('No valid pages were selected for OCR.')

        _patch(jid,
               status='running',
               total=len(target),
               processed=0,
               message=f'Starting OCR on {len(target)} page(s)…')

        writer = PdfWriter()
        page_texts: list[dict] = []
        done = 0

        for page_num in range(1, total_pages + 1):
            if _is_cancelled(jid):
                raise OCRError('Cancelled by user.')

            page = reader.pages[page_num - 1]

            if page_num not in target:
                writer.add_page(page)
                continue

            if has_text_layer(page):
                writer.add_page(page)
                try:
                    txt = page.extract_text() or ''
                except Exception:
                    txt = ''
                page_texts.append({
                    'page': page_num, 'text': txt,
                    'from_layer': True, 'skipped_ocr': True,
                })
                done += 1
                _patch(jid, processed=done, current_page=page_num,
                       progress=int(done * 100 / len(target)),
                       message=f'Page {page_num}: used existing text layer ({done}/{len(target)})')
                continue

            _patch(jid, current_page=page_num, message=f'Rendering page {page_num}…')
            try:
                imgs = convert_from_path(src_pdf_path, dpi=200,
                                         first_page=page_num, last_page=page_num)
            except Exception as e:
                raise OCRError(f'Could not render page {page_num}: {e}')
            if not imgs:
                raise OCRError(f'No image produced for page {page_num}.')
            img = imgs[0]

            _patch(jid, message=f'OCR page {page_num}…')
            try:
                ocr_text = pytesseract.image_to_string(img, lang=lang_code) or ''
                ocr_pdf = pytesseract.image_to_pdf_or_hocr(img, extension='pdf', lang=lang_code)
            except Exception as e:
                raise OCRError(f'Tesseract failed on page {page_num}: {e}')

            try:
                sub_reader = PdfReader(io.BytesIO(ocr_pdf))
                if sub_reader.pages:
                    writer.add_page(sub_reader.pages[0])
                else:
                    writer.add_page(page)
            except Exception:
                writer.add_page(page)

            page_texts.append({
                'page': page_num, 'text': ocr_text,
                'from_layer': False, 'skipped_ocr': False,
            })
            done += 1
            _patch(jid, processed=done, current_page=page_num,
                   progress=int(done * 100 / len(target)),
                   message=f'Completed page {page_num} ({done}/{len(target)})')

        safe_base = re.sub(r'[^A-Za-z0-9._-]+', '_', base_name or 'ocr')[:40] or 'ocr'
        pdf_name = f'ocr_{jid}_{safe_base}.pdf'
        txt_name = f'ocr_{jid}_{safe_base}.txt'
        pdf_path = os.path.join(generated_dir, pdf_name)
        txt_path = os.path.join(generated_dir, txt_name)

        os.makedirs(generated_dir, exist_ok=True)
        with open(pdf_path, 'wb') as fh:
            writer.write(fh)
        with open(txt_path, 'w', encoding='utf-8') as fh:
            for pt in page_texts:
                fh.write(f'--- Page {pt["page"]}')
                if pt['from_layer']:
                    fh.write(' (existing text layer)')
                fh.write(' ---\n')
                fh.write(pt['text'].rstrip())
                fh.write('\n\n')

        _patch(jid,
               status='done',
               progress=100,
               pdf_name=pdf_name,
               txt_name=txt_name,
               pages=page_texts,
               finished_at=time.time(),
               message=f'OCR complete. {len(target)} page(s) processed.')
    except OCRError as e:
        _REGISTRY.fail(jid, str(e), 'Cancelled. No output was produced.')
    except Exception as e:                  # pragma: no cover
        _REGISTRY.fail(jid, f'Unexpected error: {e}',
                       'Cancelled. No output was produced.')
    finally:
        jobs.discard(cleanup_path)