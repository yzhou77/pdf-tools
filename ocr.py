"""
OCR helpers.

Runs Tesseract (via pytesseract) on PDF pages that don't already carry a
usable text layer. Produces:

  * a *searchable PDF* – original vector pages are kept as-is, pages that
    had to be OCR'd are replaced with an image+invisible-text layer page
    generated by `pytesseract.image_to_pdf_or_hocr`.
  * a plain-text transcript per processed page.

Jobs run in a background thread so the browser can poll for progress.

External dependencies (detected at runtime, clear errors if missing):
    - tesseract (system), reachable through `pytesseract`
    - poppler-utils (for pdf2image to rasterise PDF pages)
    - pytesseract, pdf2image, Pillow (pip)
"""

from __future__ import annotations

import io
import os
import re
import threading
import time
import jobs

from PyPDF2 import PdfReader, PdfWriter
# ---------------------------------------------------------------------------
# Page-range parsing – now lives in pageselect.py (it was never OCR-specific).
# Re-exported here so existing callers keep working.
# ---------------------------------------------------------------------------
from pageselect import parse_page_range  # noqa: E402,F401

# pytesseract pulls in PIL plumbing and probes the tesseract binary, which is
# slow at import time. Load it on first use instead so start-up stays fast.
pytesseract = None
_PYT_STATE = None


def _ensure_pytesseract() -> bool:
    global pytesseract, _PYT_STATE
    if _PYT_STATE is None:
        try:
            import pytesseract as _p
            pytesseract = _p
            _PYT_STATE = True
        except Exception:
            _PYT_STATE = False
    return _PYT_STATE

try:
    from PIL import Image   # noqa: F401
    _HAS_PIL = True
except Exception:
    _HAS_PIL = False

try:
    from pdf2image import convert_from_path
    _HAS_P2I = True
except Exception:
    convert_from_path = None
    _HAS_P2I = False


class OCRError(Exception):
    """Raised for any OCR-related failure that should surface to the user."""


# ---------------------------------------------------------------------------
# Languages
# ---------------------------------------------------------------------------
LANGUAGE_LABELS = {
    'eng':     'English',
    'chi_sim': 'Chinese (Simplified)',
    'chi_tra': 'Chinese (Traditional)',
    'jpn':     'Japanese',
    'kor':     'Korean',
    'spa':     'Spanish',
    'fra':     'French',
    'deu':     'German',
}
AUTO_CODE = 'auto'


def tesseract_available() -> bool:
    if not (_ensure_pytesseract() and _HAS_PIL):
        return False
    try:
        pytesseract.get_tesseract_version()
        return True
    except Exception:
        return False


def poppler_available() -> bool:
    return _HAS_P2I


def available_languages() -> dict:
    """Return {code: label} for the supported languages that are installed."""
    if not tesseract_available():
        return {}
    try:
        installed = set(pytesseract.get_languages(config=''))
    except Exception:
        return {}
    return {c: l for c, l in LANGUAGE_LABELS.items() if c in installed}


def _resolve_language(lang: str) -> str:
    avail = available_languages()
    if not avail:
        raise OCRError(
            'No supported OCR language data is installed. Install Tesseract language '
            'packs (e.g. tesseract-ocr-eng, tesseract-ocr-chi-sim) and restart.')
    if lang == AUTO_CODE:
        return '+'.join(avail.keys())
    if lang not in avail:
        raise OCRError(f'OCR language "{lang}" is not installed on the server.')
    return lang


def has_text_layer(page, min_chars: int = 30) -> bool:
    """True when a PDF page already has enough selectable text to skip OCR."""
    try:
        text = page.extract_text() or ''
    except Exception:
        text = ''
    return sum(1 for ch in text if not ch.isspace()) >= min_chars
    """Turn '1-3,5,7-8' into a sorted unique list of valid page numbers."""
    spec = (spec or '').strip()
    if not spec:
        raise OCRError('Page range is empty.')
    pages: set[int] = set()
    for token in re.split(r'[\s,]+', spec):
        if not token:
            continue
        m = re.match(r'^(\d+)-(\d+)$', token)
        if m:
            a, b = int(m.group(1)), int(m.group(2))
            if a < 1 or b < 1 or a > b:
                raise OCRError(f'Invalid range "{token}".')
